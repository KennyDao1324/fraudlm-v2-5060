"""
Build ONE self-contained Python file for Kaggle from our repo modules.

Purpose: Kaggle cannot see this repo, and agents may not upload anything. So this script copies the
current source of our modules (model, LoRA, weight loader, ...) into a single file, followed by the job
script. Three bundles are made: the G2 feasibility check, the G4 training run and the G5 evaluation.
Thông pastes one file into a Kaggle notebook cell.
When the bundle runs it writes the modules back out as a tiny package in a temp folder and imports
them, so the code that runs on Kaggle is byte-for-byte the code in this repo.

Usage (from llm_ver2/):
    .venv/Scripts/python kaggle/make_bundle.py              # all: feasibility_bundle.py, train_bundle.py, eval_bundle.py
    .venv/Scripts/python kaggle/make_bundle.py --only train # just kaggle/train_bundle.py
Re-run it after any change to the bundled modules (the bundle is a generated file; never edit it).

Author: FraudLM v2 team (COS30049.2-1).

"""

import argparse
import datetime as dt
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Modules copied into each bundle, in repo-relative paths.
MODULES = [  # G2 feasibility bundle
    "training_model/__init__.py",
    "training_model/gpt_model.py",
    "training_model/lora.py",
    "utils/__init__.py",
    "utils/load_gpt2_weights.py",
]
TRAIN_MODULES = MODULES + [  # G4 training bundle: + the prompt template, generation and the data loader
    "utils/source_lineage.py",
    "utils/prompt.py",
    "utils/generate.py",
    "training_model/sft_data.py",
]

EVAL_MODULES = TRAIN_MODULES + [  # G5 evaluation bundle: + the evaluator's harness
    "evaluation/__init__.py",
    "evaluation/metrics.py",
    "evaluation/baselines.py",
    "evaluation/run_eval.py",
    "evaluation/make_figures.py",
    "evaluation/pick_examples.py",
]

# name -> (job script, output file, modules)
BUNDLES = {
    "feasibility": ("kaggle/feasibility.py", "kaggle/feasibility_bundle.py", MODULES),
    "train": ("training_model/train_sft.py", "kaggle/train_bundle.py", TRAIN_MODULES),
    "eval": ("kaggle/eval_job.py", "kaggle/eval_bundle.py", EVAL_MODULES),
}

REPO_ONLY_START = "# >>> REPO_ONLY"
REPO_ONLY_END = "# <<< REPO_ONLY"


def as_literal(source):
    """Source text as a readable raw triple-quoted string, or repr() if that is not safe."""
    if "'''" not in source and not source.endswith(("\\", "'")):
        return "r'''" + source + "'''"
    return repr(source)


DATA_SHA_MARKER = 'EXPECTED_DATA_SHA256 = ""  # BUNDLE_FILLS_DATA_SHA'


def repo_data_sha256():
    """sha256[:16] of train + "-" + of val in dataset/: the same fingerprint train_sft.py computes."""
    def sha(name):
        return hashlib.sha256((ROOT / "dataset" / name).read_bytes()).hexdigest()[:16]
    return sha("fraudlm_sft_train.json") + "-" + sha("fraudlm_sft_val.json")


def prepare_job(job_path):
    """Job source as it goes into the bundle: REPO_ONLY block removed and, for the training job, the
    expected data hash filled in (G4 review R2), so Kaggle refuses a dataset that differs from the repo."""
    text = strip_repo_only(Path(job_path).read_text(encoding="utf-8"))
    if DATA_SHA_MARKER in text:
        text = text.replace(DATA_SHA_MARKER,
                            f'EXPECTED_DATA_SHA256 = "{repo_data_sha256()}"  # filled by make_bundle.py')
    return text


def strip_repo_only(job_source):
    """Remove the REPO_ONLY block (repo sys.path setup) from the job script."""
    out, skipping = [], False
    for line in job_source.splitlines(keepends=True):
        if line.strip().startswith(REPO_ONLY_START):
            skipping = True
            continue
        if line.strip().startswith(REPO_ONLY_END):
            skipping = False
            continue
        if not skipping:
            out.append(line)
    if skipping:
        raise SystemExit(f"{REPO_ONLY_START} block is not closed in the job script")
    return "".join(out)


PREAMBLE = '''\
# =====================================================================================
# FraudLM v2 Kaggle bundle: {job}
# GENERATED by kaggle/make_bundle.py on {when}. Do not edit; re-generate from the repo.
# Paste this whole file into ONE Kaggle notebook cell and run it (Internet ON, GPU on).
#
# Contents: Part A installs missing packages; Part B writes our own modules
# ({module_list}) to a temp folder and imports them; Part C is {job}.
#
# Author: FraudLM v2 team (COS30049.2-1). Model/LoRA/loader code follows Raschka, S. (2024)
# *Build a Large Language Model (From Scratch)*, Manning; code repo Apache-2.0.
#
# =====================================================================================

# -------------------------------------------------------------------------------------
# Part A. Packages. Kaggle images already have torch, safetensors and huggingface_hub;
# tiktoken (the GPT-2 tokenizer, PLAN D4) is installed only if it is missing.
# -------------------------------------------------------------------------------------
import importlib.util as _ilu
import subprocess as _sp
import sys as _sys

for _pkg in ("tiktoken", "safetensors", "huggingface_hub"):
    if _ilu.find_spec(_pkg) is None:
        print(f"[setup] pip install {{_pkg}}")
        _sp.check_call([_sys.executable, "-m", "pip", "install", "-q", _pkg])

# -------------------------------------------------------------------------------------
# Part B. Our modules, copied verbatim from the repo (sha256 shown for each file).
# They are written to <temp>/fraudlm_src/ and that folder goes first on sys.path, so
# `from training_model.gpt_model import ...` works exactly as in the repo.
# -------------------------------------------------------------------------------------
import os as _os
import tempfile as _tempfile

_SRC_DIR = _os.path.join(_tempfile.gettempdir(), "fraudlm_src")
_BUNDLED_FILES = {{}}
'''

FILE_ENTRY = '''
# ---- {path}  (sha256 {sha}) ----
_BUNDLED_FILES["{path}"] = {literal}
'''

WRITE_FILES = '''
for _rel, _text in _BUNDLED_FILES.items():
    _dst = _os.path.join(_SRC_DIR, *_rel.split("/"))
    _os.makedirs(_os.path.dirname(_dst), exist_ok=True)
    with open(_dst, "w", encoding="utf-8") as _f:
        _f.write(_text)
if _SRC_DIR not in _sys.path:
    _sys.path.insert(0, _SRC_DIR)
# Forget any earlier copy imported in this notebook session, so a re-run uses this bundle.
for _name in [m for m in list(_sys.modules) if m.split(".")[0] in ("training_model", "utils", "evaluation")]:
    del _sys.modules[_name]
print(f"[setup] wrote {len(_BUNDLED_FILES)} module files to {_SRC_DIR}")

# -------------------------------------------------------------------------------------
# Part C. The job script
# -------------------------------------------------------------------------------------
'''


def _without_stamp(text):
    """Bundle text without its "GENERATED ... on <time>" line (the only line that changes on a rebuild)."""
    return "\n".join(l for l in text.splitlines() if not l.startswith("# GENERATED by kaggle/make_bundle.py"))


def build(job_path, out_path, modules=None):
    modules = MODULES if modules is None else modules
    job_path, out_path = Path(job_path), Path(out_path)
    parts = [PREAMBLE.format(
        job=job_path.relative_to(ROOT).as_posix(),
        when=dt.datetime.now().strftime("%Y-%m-%d %H:%M"),
        module_list=", ".join(m for m in modules if not m.endswith("__init__.py")),
    )]
    for rel in modules:
        text = (ROOT / rel).read_text(encoding="utf-8")
        sha = hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]
        parts.append(FILE_ENTRY.format(path=rel, sha=sha, literal=as_literal(text)))
    parts.append(WRITE_FILES)
    parts.append(prepare_job(job_path))
    bundle = "".join(parts)
    compile(bundle, str(out_path), "exec")  # fail here, not on Kaggle, if the result is not valid Python
    if out_path.exists() and _without_stamp(out_path.read_text(encoding="utf-8")) == _without_stamp(bundle):
        # Same code: keep the old file byte for byte, so a bundle already pushed to Kaggle stays identical.
        print(f"[bundle] {out_path.name} unchanged (kept as it was)")
        return
    out_path.write_text(bundle, encoding="utf-8", newline="\n")
    print(f"[bundle] wrote {out_path} ({len(bundle):,} chars, {bundle.count(chr(10)):,} lines) "
          f"from {len(modules)} modules + {job_path.name}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Inline repo modules + a job script into one Kaggle file")
    ap.add_argument("--only", choices=list(BUNDLES), help="build just one bundle (default: all)")
    a = ap.parse_args()
    for name, (job, out, mods) in BUNDLES.items():
        if a.only in (None, name):
            build(ROOT / job, ROOT / out, mods)
